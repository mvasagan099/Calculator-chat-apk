#!/usr/bin/env python3
"""Validate public Flutter config and install the Android Firebase console file.

Server credentials and test-account passwords are rejected, never serialized.
This script does not contact, create or deploy any provider project.
"""
import argparse
import base64
import json
import os
from pathlib import Path
import re
import sys

PACKAGE = 'app.calculatorspace.calculator_messenger'
PUBLIC_FIELDS = {
    'LOCAL_UI_PREVIEW', 'SUPABASE_URL', 'SUPABASE_ANON_KEY',
    'FIREBASE_API_KEY', 'FIREBASE_APP_ID', 'FIREBASE_SENDER_ID', 'FIREBASE_PROJECT_ID',
}
FIREBASE_FIELDS = ('FIREBASE_API_KEY', 'FIREBASE_APP_ID', 'FIREBASE_SENDER_ID', 'FIREBASE_PROJECT_ID')
MARKER = '<!-- Generated by prepare-client-config.py. Public identifiers only. -->'


def validate_public_key(key):
    if not isinstance(key, str) or not key:
        raise ValueError('A public Supabase publishable/anon key is required')
    if key.startswith('sb_publishable_') and len(key) > 25:
        return
    try:
        payload = key.split('.')[1]
        claims = json.loads(base64.urlsafe_b64decode(payload + '=' * (-len(payload) % 4)))
        if isinstance(claims, dict) and claims.get('role') == 'anon' and len(key.split('.')) == 3:
            return
    except (ValueError, IndexError, TypeError):
        pass
    raise ValueError('Use a Supabase public publishable/anon key; secret/service-role keys are forbidden')


def prepare(data, mode, firebase_android=None):
    unknown = set(data) - PUBLIC_FIELDS
    if unknown:
        raise ValueError('Unknown/private fields are forbidden in client config')
    if not isinstance(data.get('LOCAL_UI_PREVIEW', mode == 'preview'), bool):
        raise ValueError('LOCAL_UI_PREVIEW must be a JSON boolean')
    preview = mode == 'preview'
    if data.get('LOCAL_UI_PREVIEW', preview) != preview:
        raise ValueError('Selected build mode and LOCAL_UI_PREVIEW disagree')
    if any(not isinstance(v, str) for k, v in data.items() if k != 'LOCAL_UI_PREVIEW'):
        raise ValueError('Public identifiers must be strings')
    if preview:
        if any(v for k, v in data.items() if k != 'LOCAL_UI_PREVIEW') or firebase_android:
            raise ValueError('Preview builds must not contain connected provider configuration')
        return {'LOCAL_UI_PREVIEW': True}, None
    from urllib.parse import urlsplit
    url = urlsplit(data.get('SUPABASE_URL', ''))
    if url.scheme != 'https' or not url.hostname or url.username or url.password or url.query or url.fragment or url.path not in ('', '/'):
        raise ValueError('A valid HTTPS Supabase project origin is required')
    validate_public_key(data.get('SUPABASE_ANON_KEY'))
    if any('YOUR_' in v.upper() for k, v in data.items() if k != 'LOCAL_UI_PREVIEW'):
        raise ValueError('Replace example provider identifiers before building')
    result = {'LOCAL_UI_PREVIEW': False, **{k: v for k, v in data.items() if k != 'LOCAL_UI_PREVIEW' and v}}
    if firebase_android:
        if any(key in json.dumps(firebase_android) for key in ['private_key', 'service_account', 'client_secret']):
            raise ValueError('Server credentials are forbidden in Android configuration')
        project = firebase_android['project_info']
        apps = [c for c in firebase_android['client'] if c['client_info'].get('android_client_info', {}).get('package_name') == PACKAGE]
        if len(apps) != 1:
            raise ValueError('Firebase Android app must match the Android application ID exactly')
        app = apps[0]
        console = dict(zip(FIREBASE_FIELDS, [app['api_key'][0]['current_key'], app['client_info']['mobilesdk_app_id'], project['project_number'], project['project_id']]))
        for key, value in console.items():
            if result.get(key, value) != value:
                raise ValueError('Firebase Dart identifiers disagree with the Firebase Android configuration')
        result.update(console)
    elif any(result.get(k) for k in FIREBASE_FIELDS):
        raise ValueError('Firebase requires the console Android config to verify package identity and generate native resources')
    if not all(result.get(k) for k in FIREBASE_FIELDS):
        return result, None
    if not re.fullmatch(r'1:' + re.escape(result['FIREBASE_SENDER_ID']) + r':android:[A-Za-z0-9]+', result['FIREBASE_APP_ID']):
        raise ValueError('Firebase Android app ID and sender ID disagree')
    return result, firebase_android


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mode', required=True, choices=['preview', 'connected'])
    parser.add_argument('--input', type=Path)
    parser.add_argument('--from-environment', action='store_true')
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--firebase-android', type=Path, help='Console google-services.json, never a service-account JSON')
    parser.add_argument('--android-output', type=Path, default=Path('android/app/google-services.json'))
    parser.add_argument('--resources', type=Path, default=Path('android/app/src/main/res/values/firebase_public.xml'))
    args = parser.parse_args()
    try:
        if args.input and args.from_environment:
            raise ValueError('Choose either input file or environment')
        data = json.loads(args.input.read_text()) if args.input else {}
        if not isinstance(data, dict):
            raise ValueError('Client configuration must be an object')
        if args.from_environment:
            data = {k: os.environ[k] for k in PUBLIC_FIELDS - {'LOCAL_UI_PREVIEW'} if os.environ.get(k)} if args.mode == 'connected' else {}
        firebase_source = args.firebase_android
        if firebase_source is None and args.mode == 'connected' and not os.environ.get('FIREBASE_ANDROID_CONFIG') and args.android_output.is_file():
            firebase_source = args.android_output
        firebase = json.loads(firebase_source.read_text()) if firebase_source else None
        if firebase is None and args.mode == 'connected' and os.environ.get('FIREBASE_ANDROID_CONFIG'):
            firebase = json.loads(os.environ['FIREBASE_ANDROID_CONFIG'])
        firebase_supplied = firebase_source is not None or (
            args.mode == 'connected' and bool(os.environ.get('FIREBASE_ANDROID_CONFIG'))
        )
        if firebase_supplied and (
            not isinstance(firebase, dict)
            or not isinstance(firebase.get('project_info'), dict)
            or not isinstance(firebase.get('client'), list)
            or not firebase['client']
        ):
            raise ValueError('Expected an Android console configuration object')
        config, android = prepare(data, args.mode, firebase)
        if android and args.android_output.is_file() and json.loads(args.android_output.read_text()) != firebase:
            raise ValueError('Refusing to replace a different existing Android Firebase configuration')
        if not android and args.android_output.is_file():
            raise ValueError('Remove the owner Firebase console file explicitly before a provider-free build')
        if args.resources.exists() and MARKER not in args.resources.read_text():
            raise ValueError('Refusing to overwrite an existing resource file not generated by this script')
        if args.input and args.input.resolve() == args.output.resolve():
            raise ValueError('Output must differ from the input configuration')
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(config, indent=2) + '\n')
        if android and not args.android_output.is_file():
            args.android_output.parent.mkdir(parents=True, exist_ok=True)
            args.android_output.write_text(json.dumps(firebase, indent=2) + '\n')
        if args.resources.exists():
            args.resources.unlink()  # Retire only our old generated XML to avoid duplicate resources.
        print('Validated public configuration: ' + args.mode + '; Google Services: ' + ('configured' if android else 'disabled'))
    except (ValueError, KeyError, TypeError, OSError):
        print('Client configuration rejected. Connected builds require a public HTTPS Supabase URL/key. FIREBASE_ANDROID_CONFIG must be the complete raw google-services.json object (not base64 or a service account), matching app.calculatorspace.calculator_messenger. No values were logged.', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
