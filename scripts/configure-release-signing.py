#!/usr/bin/env python3
"""Materialize owner-supplied CI signing inputs privately; never generate a key.

The CLI verifies the supplied certificate with keytool before allowing a build.
No secrets or raw subprocess errors are printed. Cleanup touches only files this
helper recorded, never an existing owner's key.properties.
"""
import argparse
import base64
import binascii
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

MARKER = '# Generated by configure-release-signing.py; never commit.\n'


def java_value(value):
    result = ''
    for character in value:
        if character in '\\:=#! ':
            result += '\\' + character
        elif character in '\n\r\t\f':
            result += {'\n': r'\n', '\r': r'\r', '\t': r'\t', '\f': r'\f'}[character]
        elif ord(character) < 32 or ord(character) > 126:
            encoded = character.encode('utf-16-be')
            result += ''.join('\\u' + encoded[i:i+2].hex() for i in range(0, len(encoded), 2))
        else:
            result += character
    return result


def private_write(path, data):
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'wb') as output:
        output.write(data)


def materialize(values, directory, properties):
    required = ['ANDROID_RELEASE_KEYSTORE_B64', 'ANDROID_KEY_ALIAS', 'ANDROID_STORE_PASSWORD', 'ANDROID_KEY_PASSWORD', 'ANDROID_CERT_SHA256']
    if any(not isinstance(values.get(key), str) or not values[key] for key in required):
        raise ValueError('Missing signing configuration')
    fingerprint = values['ANDROID_CERT_SHA256'].replace(':', '').lower()
    if not re.fullmatch('[0-9a-f]{64}', fingerprint):
        raise ValueError('Invalid certificate fingerprint')
    if properties.exists() or properties.is_symlink():
        raise ValueError('Existing signing configuration preserved')
    encoded = values['ANDROID_RELEASE_KEYSTORE_B64']
    if len(encoded) > 3 * 1024 * 1024:
        raise ValueError('Keystore input too large')
    raw = base64.b64decode(encoded, validate=True)
    if not raw or len(raw) > 2 * 1024 * 1024:
        raise ValueError('Invalid keystore input')
    directory.mkdir(parents=True, exist_ok=True)
    private_dir = Path(tempfile.mkdtemp(prefix='calculator-signing-', dir=directory)).resolve()
    key = private_dir / 'release.jks'
    created_properties = False
    try:
        private_write(key, raw)
        contents = MARKER + ''.join(f'{name}={java_value(value)}\n' for name, value in {
            'storeFile': str(key), 'storePassword': values['ANDROID_STORE_PASSWORD'],
            'keyAlias': values['ANDROID_KEY_ALIAS'], 'keyPassword': values['ANDROID_KEY_PASSWORD'],
        }.items())
        private_write(properties, contents.encode('ascii'))
        created_properties = True
        return {'keystore': str(key), 'properties': str(properties.resolve())}, fingerprint
    except Exception:
        if created_properties:
            properties.unlink()
        key.unlink(missing_ok=True)
        private_dir.rmdir()
        raise


def cleanup(record, directory, properties):
    key = Path(record['keystore'])
    config = Path(record['properties'])
    root = directory.resolve()
    if key.name != 'release.jks' or not key.parent.name.startswith('calculator-signing-') or key.parent.parent != root or key.is_symlink() or config != properties.resolve():
        raise ValueError('Cleanup scope mismatch')
    if config.exists():
        if not config.read_text().startswith(MARKER):
            raise ValueError('Existing configuration preserved')
        config.unlink()
    key.unlink(missing_ok=True)
    key.parent.rmdir()  # Refuse to remove any unexpected additional files.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--directory', required=True, type=Path)
    parser.add_argument('--properties', type=Path, default=Path('android/key.properties'))
    parser.add_argument('--cleanup', action='store_true')
    args = parser.parse_args()
    manifest = args.directory / 'calculator-signing-record.json'
    record = None
    try:
        if args.cleanup:
            if manifest.exists():
                cleanup(json.loads(manifest.read_text()), args.directory, args.properties)
                manifest.unlink()
            return 0
        if manifest.exists():
            raise ValueError('Signing operation already pending')
        record, expected = materialize(os.environ, args.directory, args.properties)
        keytool = shutil.which('keytool')
        if not keytool:
            raise ValueError('JDK keytool required')
        certificate = subprocess.run([keytool, '-exportcert', '-keystore', record['keystore'], '-alias', os.environ['ANDROID_KEY_ALIAS'], '-storepass:env', 'ANDROID_STORE_PASSWORD'], check=True, capture_output=True, timeout=30).stdout
        if hashlib.sha256(certificate).hexdigest() != expected:
            raise ValueError('Certificate does not match owner fingerprint')
        private_write(manifest, json.dumps(record).encode())
        print('Signing inputs verified and stored with private file permissions. No release has been built.')
        return 0
    except (ValueError, TypeError, KeyError, OSError, binascii.Error, subprocess.SubprocessError):
        if record is not None:
            try:
                cleanup(record, args.directory, args.properties)
            except (ValueError, OSError):
                pass
        print('Signing setup rejected. Check protected signing secrets, certificate fingerprint and JDK; existing files were preserved. No values were logged.', file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
